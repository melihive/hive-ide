    @classmethod
    def _agent_command(cls, record: dict[str, Any]) -> str:
        driver = record.get("driver") or {}
        argv = driver.get("launch_argv") or [os.environ.get("SHELL", "/bin/sh")]
        attach = cls._attach_argv(driver)
        if attach:
            # An attach reconnects to a turn already in flight, so a handoff prompt
            # does not belong on it — that is a thing you say to a fresh driver.
            argv = attach
        else:
            argv = cls._argv_with_handoff_prompt(argv, record)
        command = shlex.join(argv)
        handoff = record.get("handoff")
        if isinstance(handoff, dict) and handoff:
            lines = [
                "",
                "HIVE IDE handoff",
                f"- session: {handoff.get('session_name') or record.get('name')} ({record.get('id')})",
                f"- driver: {handoff.get('from_driver') or 'unknown'} -> {handoff.get('to_driver') or driver.get('id') or 'unknown'}",
                f"- cwd: {handoff.get('working_dir') or record.get('working_dir') or ''}",
            ]
            if handoff.get("plan"):
                lines.append(f"- plan: {handoff['plan']}")
            if handoff.get("active_task"):
                lines.append(f"- active task: {handoff['active_task']}")
            if handoff.get("target_driver_prompt"):
                driver_id = driver.get("id") or "driver"
                lines.extend(
                    [
                        "",
                        f"Handoff prompt sent to {driver_id}; agent should start below.",
                    ]
                )
            prefix = "printf %s " + shlex.quote("\n".join(lines) + "\n\n")
            command = f"{prefix}; {command}"
        return cls._interactive_command(
            f"{command}; status=$?; "
            'if [ "$status" -ne 0 ]; then '
            "printf '\\nhive-ide: driver command failed with exit %s\\n' \"$status\"; "
            "fi; "
            'exec "${SHELL:-/bin/sh}"'
        )

    PROMPT_DRIVERS = ("claude", "codex")
    LAUNCH_PROMPT_MAX = 4000

    @classmethod
    def launch_prompt_problem(cls, prompt: Any, driver_id: str | None) -> str | None:
        """Why `prompt` cannot be a session's launch prompt, or None when it can.

        It is passed as the driver's positional prompt argument, never typed, so
        the only hazards are a driver that takes no prompt, a value the driver
        would parse as an option (a leading `-`), and bytes argv cannot carry.
        """
        if driver_id not in cls.PROMPT_DRIVERS:
            return "only the claude and codex drivers take a launch prompt"
        if not isinstance(prompt, str) or not prompt.strip():
            return "empty"
        if len(prompt) > cls.LAUNCH_PROMPT_MAX:
            return f"longer than {cls.LAUNCH_PROMPT_MAX} characters"
        if prompt != prompt.strip():
            return "leading or trailing whitespace"
        if prompt.startswith("-"):
            return "must not start with - (the driver would read it as an option)"
        if any(ord(ch) < 0x20 and ch not in "\n\t" for ch in prompt) or "\x7f" in prompt:
            return "control characters are not allowed"
        return None

    @classmethod
    def _argv_with_handoff_prompt(
        cls, argv: list[str], record: dict[str, Any]
    ) -> list[str]:
        """Append the one prompt this launch carries: a handoff's, else the
        session's launch prompt (`create --prompt`). Never typed into the pane."""
        driver_id = (record.get("driver") or {}).get("id")
        if driver_id not in cls.PROMPT_DRIVERS:
            return argv
        handoff = record.get("handoff")
        prompt = handoff.get("target_driver_prompt") if isinstance(handoff, dict) else None
        if not isinstance(prompt, str) or not prompt.strip():
            prompt = record.get("launch_prompt")
            if cls.launch_prompt_problem(prompt, driver_id):
                return argv
        return [*argv, prompt]

    def _plan_command(
        self, record: dict[str, Any], *, line: int | None = None
    ) -> str:
        try:
            path = self.plan_path(record)
        except UsageError:
            path = None
        if path is not None:
            editor = self._plan_pane_editor_argv(self._editor_argv())
            if line and line > 1 and Path(editor[0]).name in self.PLUS_LINE_EDITORS:
                editor.append(f"+{line}")
            return self._interactive_command(
                f"{shlex.join([*editor, str(path)])}; "
                'exec "${SHELL:-/bin/sh}"'
            )
        return self._interactive_command(
            'printf "\\n  No plan linked.\\n"; exec "${SHELL:-/bin/sh}"'
        )

    def safe_working_dir(self, record: dict[str, Any]) -> str:
        working_dir = Path(str(record.get("working_dir") or "")).expanduser()
        if working_dir.is_dir():
            return str(working_dir.resolve())
        return self.store.workspace_key

    @staticmethod
    def resolve_plan_path(reference: str | Path, record: dict[str, Any]) -> Path:
        path = Path(reference).expanduser()
        if path.is_absolute():
            candidates = [path]
        else:
            workspace = record.get("workspace_key")
            if not workspace:
                raise UsageError("Session workspace key is missing; cannot resolve plan path.")
            candidates = [Path(str(workspace)).expanduser() / path]
            working_dir = Path(str(record.get("working_dir") or "")).expanduser()
            if working_dir.is_dir():
                candidates.append(working_dir / path)

        for candidate in candidates:
            resolved = candidate.resolve()
            if resolved.is_file():
                return resolved
        checked = ", ".join(str(candidate.resolve()) for candidate in candidates)
        raise UsageError(f"Plan file does not exist: {checked}")

    @staticmethod
    def plan_path(record: dict[str, Any]) -> Path:
        reference = (record.get("plan") or {}).get("path")
        if not reference:
            raise UsageError("No plan is linked to this session.")
        return Frame.resolve_plan_path(reference, record)

    def _editor_argv(self) -> list[str]:
        configured = (self.settings.get("editor") or {}).get("argv")
        if (
            isinstance(configured, list)
            and configured
            and all(isinstance(value, str) for value in configured)
        ):
            return list(configured)
        return resolve_editor_argv({})

    @classmethod
    def _plan_pane_editor_argv(cls, editor: list[str]) -> list[str]:
        if not editor:
            return editor
        flags = cls.PLAN_PANE_READONLY_FLAGS.get(Path(editor[0]).name)
        if not flags:
            return list(editor)
        return [editor[0], *flags, *editor[1:]]

    def _send_micro_command(self, pane_id: str, command: str) -> None:
        self.tmux(["send-keys", "-t", pane_id, "C-e"])
        self.tmux(["send-keys", "-t", pane_id, command, "Enter"])

    def _pane_has_micro(self, pane_id: str) -> bool:
        current = self.tmux(
            ["display-message", "-p", "-t", pane_id, "#{pane_current_command}"]
        ).stdout.strip()
        if current == "micro":
            return True
        pid = self._pane_pid(pane_id)
        if pid is None:
            return False
        return any(
            self._process_command_name(candidate) == "micro"
            for candidate in self._process_tree(pid)
        )

    @staticmethod
    def _process_command_name(pid: int) -> str | None:
        try:
            name = Path(f"/proc/{pid}/comm").read_text(encoding="utf-8").strip()
        except OSError:
            name = ""
        if name:
            return name
        try:
            raw = Path(f"/proc/{pid}/cmdline").read_bytes().split(b"\0", 1)[0]
        except OSError:
            return None
        if not raw:
            return None
        return Path(raw.decode("utf-8", errors="replace")).name

    @staticmethod
    def plan_focus_line(path: Path) -> int:
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except OSError:
            return 1
        todo = next(
            (
                index
                for index, text in enumerate(lines)
                if text.lstrip().startswith("- [ ]")
            ),
            None,
        )
        if todo is not None:
            return todo + 1
        done = next(
            (
                index
                for index, text in reversed(list(enumerate(lines)))
                if text.lstrip().lower().startswith("- [x]")
            ),
            None,
        )
        if done is not None:
            return done + 1
        tasks = next(
            (
                index
                for index, text in enumerate(lines)
                if text.strip() == "## Tasks"
            ),
            None,
        )
        return tasks + 1 if tasks is not None else 1

    @staticmethod
    def ensure_scratchpad(path: Path) -> int:
        try:
            text = path.read_text(encoding="utf-8")
        except OSError as exc:
            raise HiveIdeError(f"Could not read plan {path}: {exc}") from exc
        lines = text.splitlines()
        scratchpad = next(
            (
                index
                for index, line in enumerate(lines)
                if line.strip().lower() == "## scratchpad"
            ),
            None,
        )
        if scratchpad is not None:
            return scratchpad + 1
        insert_at = next(
            (
                index
                for index, line in enumerate(lines)
                if line.strip() == "## Tasks"
            ),
            None,
        )
        if insert_at is None:
            insert_at = next(
                (
                    index
                    for index, line in enumerate(lines)
                    if line.strip().lower() in {"## status log", "## status"}
                ),
                None,
            )
        if insert_at is None:
            insert_at = len(lines)
        insert = ["## Scratchpad", ""]
        if insert_at > 0 and lines[insert_at - 1].strip():
            insert.insert(0, "")
        new_lines = [*lines[:insert_at], *insert, *lines[insert_at:]]
        try:
            path.write_text("\n".join(new_lines) + "\n", encoding="utf-8")
        except OSError as exc:
            raise HiveIdeError(f"Could not update plan {path}: {exc}") from exc
        return insert_at + (2 if insert[0] == "" else 1)

    @staticmethod
    def tasks_line(path: Path) -> int | None:
        try:
            text = path.read_text(encoding="utf-8")
        except OSError as exc:
            raise HiveIdeError(f"Could not read plan {path}: {exc}") from exc
        lines = text.splitlines()
        if not any(line.strip() == "## Tasks" for line in lines):
            return None
        return Frame.plan_focus_line(path)

    def scratchpad_editor_argv(self) -> list[str]:
        if shutil.which("micro"):
            return ["micro"]
        return self._editor_argv()

    def popup_size(self, *, width: str, height: str) -> tuple[str, str]:
        result = self.tmux(["display-message", "-p", "#{client_width}"])
        if result.returncode != 0:
            return width, height
        raw = result.stdout.strip()
        if raw.isdigit() and int(raw) < self.SIDEBAR_ZOOM_MAX:
            return "96%", "92%"
        return width, height

    def plan_popup(
        self, record: dict[str, Any], *, mode: str = "scratchpad"
    ) -> dict[str, Any]:
        path = self.plan_path(record)
        if mode == "scratchpad":
            line = self.ensure_scratchpad(path)
        elif mode == "tasks":
            line = self.tasks_line(path)
            if line is None:
                return {
                    "ok": False,
                    "reason": "no_tasks",
                    "session_id": record["id"],
                    "plan": str(path),
                }
        elif mode == "plan":
            line = 1
        else:
            raise UsageError(f"Unknown plan popup mode {mode!r}.")
        editor = self.scratchpad_editor_argv()
        if line > 1 and Path(editor[0]).name in self.PLUS_LINE_EDITORS:
            editor.append(f"+{line}")
        command = shlex.join([*editor, str(path)])
        width, height = self.popup_size(width="72%", height="70%")
        result = self.tmux(
            [
                "display-popup",
                "-E",
                "-w",
                width,
                "-h",
                height,
                command,
            ]
        )
        if result.returncode != 0:
            raise HiveIdeError(result.stderr.strip() or "Could not open Scratchpad.")
        return {
            "session_id": record["id"],
            "plan": str(path),
            "line": line,
            "opened": f"{mode}-popup",
        }

    def scratchpad(self, record: dict[str, Any]) -> dict[str, Any]:
        return self.plan_popup(record, mode="scratchpad")

    @serialized
    def current_plan(
        self, record: dict[str, Any], *, focus: bool = False, force: bool = False
    ) -> dict[str, Any]:
        lease = LeaseStore(self.store).live(record["id"])
        if lease and focus and not force:
            pane = (self.role_panes(record["id"]) or {}).get("plan")
            if pane:
                self.tmux(["select-pane", "-t", pane])
            return {
                "session_id": record["id"],
                "reason": "pane_leased",
                "lease": LeaseStore.summary(lease),
                "opened": "plan-pane",
            }
        PaneLeases(self).check(record["id"], force=force)
        path = self.plan_path(record)
        line = self.plan_focus_line(path) if focus else None
        pane_id = (self.role_panes(record["id"]) or {}).get("plan")
        # Steering a live micro is harmless, so it only needs "not provably the
        # caller's pane"; the respawn below kills the pane, so it needs a settled
        # "not the caller's pane" and otherwise falls back to a terminal editor.
        verdict = self.pane_is_caller(pane_id) if pane_id else None
        if pane_id and verdict is not True:
            if self._pane_has_micro(pane_id):
                self._send_micro_command(pane_id, "set readonly true")
                if focus:
                    self._send_micro_command(pane_id, f"goto {line}")
                    self.tmux(["select-pane", "-t", pane_id])
                return {
                    "session_id": record["id"],
                    "plan": str(path),
                    "line": line,
                    "opened": "plan-pane",
                }
        if pane_id and verdict is False:
            result = self.tmux(
                [
                    "respawn-pane",
                    "-k",
                    "-t",
                    pane_id,
                    "-c",
                    self.safe_working_dir(record),
                    *self._environment(record, role="plan"),
                    "sh",
                    "-c",
                    self._plan_command(record, line=line),
                ]
            )
            if result.returncode != 0:
                raise HiveIdeError(
                    result.stderr.strip() or "Could not reopen the plan pane."
                )
            self.tmux(["select-pane", "-T", self._plan_title(record), "-t", pane_id])
            if focus:
                self.tmux(["select-pane", "-t", pane_id])
            return {
                "session_id": record["id"],
                "plan": str(path),
                "line": line,
                "opened": "plan-pane",
            }
        editor = self._editor_argv()
        if line and line > 1 and Path(editor[0]).name in self.PLUS_LINE_EDITORS:
            editor.append(f"+{line}")
        result = subprocess.run([*editor, str(path)])
        if result.returncode != 0:
            raise HiveIdeError(f"The plan editor exited with status {result.returncode}.")
        return {
            "session_id": record["id"],
            "plan": str(path),
            "line": line,
            "opened": "terminal",
        }

    def current_chat(self, record: dict[str, Any]) -> dict[str, Any]:
        driver = record.get("driver") or {}
        argv = list(driver.get("launch_argv") or [])
        if not argv:
            raise UsageError("The session has no agent command to resume.")
        pane_id = (self.role_panes(record["id"]) or {}).get("agent")
        verdict = self.pane_is_caller(pane_id) if pane_id else None
        if pane_id and verdict is not True:
            current = self.tmux(
                ["display-message", "-p", "-t", pane_id, "#{pane_current_command}"]
            ).stdout.strip()
            if self.is_shell_agent_pane(record, current):
                if not self.respawn_agent(record, pane_id):
                    # Relaunching kills the pane's shell, which may be this very
                    # terminal: the caller's location is not settled.
                    raise UsageError(
                        "The agent pane is idle but this command may be running "
                        "inside it; run `hive-ide chat` from another pane or a "
                        "plain terminal to relaunch the agent."
                    )
                self._clear_consumed_handoff(record)
                self.clear_sleep(record)
                self.tmux(["select-pane", "-t", pane_id])
                return {
                    "session_id": record["id"],
                    "driver": driver.get("id"),
                    "opened": "agent-pane",
                }
            self.clear_sleep(record)
            self.tmux(["select-pane", "-t", pane_id])
            return {
                "session_id": record["id"],
                "driver": driver.get("id"),
                "opened": "existing-agent-pane",
            }
        result = subprocess.run(argv, cwd=record["working_dir"])
        if result.returncode != 0:
            if driver.get("id") == "claude":
                fallback_argv = ["claude"]
                name = " ".join(str(record.get("name") or "").split())
                if name:
                    fallback_argv.extend(["--name", name])
                fallback = subprocess.run(fallback_argv, cwd=record["working_dir"])
                if fallback.returncode == 0:
                    self.clear_sleep(record)
                    return {
                        "session_id": record["id"],
                        "driver": driver.get("id"),
                        "opened": "claude",
                    }
            raise HiveIdeError(f"The agent exited with status {result.returncode}.")
        self.clear_sleep(record)
        return {
            "session_id": record["id"],
            "driver": driver.get("id"),
            "opened": "terminal",
        }

    def clear_sleep(self, record: dict[str, Any]) -> bool:
        if (record.get("sleep") or {}).get("state") != "sleeping":
            return False
        current = self.store.find_session(record["id"])
        if current is None:
            return False
        current.pop("sleep", None)
        current["last_active"] = utc_now()
        self.store.write("sessions", current["id"], current)
        self.store.delete("status", current["id"])
        return True

