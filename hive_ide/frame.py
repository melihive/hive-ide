    def __init__(self, store: StateStore, *, socket: str | None = None):
        self.store = store
        self.settings = store.read_path(store.config_snapshot_path()) or {}
        saved_tmux = self.settings.get("tmux") or {}
        self.socket = (
            socket
            or saved_tmux.get("socket")
            or f"hive-ide-{store.workspace_hash[:8]}"
        )
        self.target = f"hive-ide-{store.workspace_hash[:8]}"
        self.python = sys.executable

    def _ide_conf(self) -> Path | None:
        """Copy the user's tmux config while disabling continuum for this server."""
        source = next(
            (
                path
                for relative in self.USER_CONFS
                if (path := Path.home() / relative).is_file()
            ),
            None,
        )
        if source is None:
            return None
        output = self.store.workspace_dir / "ide.conf"
        try:
            original = source.read_text(encoding="utf-8").splitlines()
        except OSError as exc:
            raise UsageError(f"Could not read tmux config {source}: {exc}") from exc
        lines = [
            f"# Generated by hive-ide from {source}; do not edit.",
            "# tmux-continuum restore and autosave are disabled for this server only.",
            "",
        ]
        save_disabled = False
        for line in original:
            if re.match(r"^\s*set\b.*@continuum-restore", line):
                lines.extend(
                    [f"# [hive-ide] was: {line.strip()}", "set -g @continuum-restore 'off'"]
                )
            elif re.match(r"^\s*set\b.*@continuum-save-interval", line):
                lines.append(f"# [hive-ide] was: {line.strip()}")
            else:
                if re.match(r"^\s*run\b.*tpm", line) and not save_disabled:
                    lines.append(
                        "set -g @continuum-save-interval '0' # hive-ide never autosaves"
                    )
                    save_disabled = True
                lines.append(line)
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return output

    def tmux(
        self,
        args: list[str],
        *,
        clean_start: bool = False,
        timeout: float | None = None,
    ) -> subprocess.CompletedProcess[str]:
        """Run tmux on this frame's socket.

        `timeout` bounds probes made while holding the workspace lock; a timed-out
        call comes back as a failed result (returncode 124), never an exception,
        so callers' existing failure handling covers a wedged server.
        """
        generated = self._ide_conf() if clean_start else None
        config = ["-f", str(generated)] if generated else []
        argv = ["tmux", "-L", self.socket, *config, *args]
        try:
            return subprocess.run(argv, capture_output=True, text=True, timeout=timeout)
        except subprocess.TimeoutExpired:
            return subprocess.CompletedProcess(
                argv, 124, stdout="", stderr=f"tmux timed out after {timeout}s"
            )

    def require_tmux(self) -> None:
        if shutil.which("tmux") is None:
            raise UsageError("tmux is required but was not found on PATH.")
        handshake = subprocess.run(
            PythonCommand.cli_argv(["version"], python=self.python),
            capture_output=True,
            text=True,
        )
        if handshake.returncode != 0:
            raise UsageError(
                "The selected Python interpreter cannot import hive_ide. Install the "
                "package into that environment."
            )

    def exists(self) -> bool:
        return self.tmux(["has-session", "-t", self.target]).returncode == 0

    def tmux_sessions(self) -> list[dict[str, Any]]:
        """Every tmux session on this frame's socket, newest first."""
        result = self.tmux(
            [
                "list-sessions",
                "-F",
                "#{session_name}\t#{session_created}\t#{session_attached}\t"
                "#{session_windows}",
            ]
        )
        if result.returncode != 0:
            return []
        rows: list[dict[str, Any]] = []
        for line in result.stdout.splitlines():
            fields = line.split("\t")
            if len(fields) != 4:
                continue
            name, created, attached, windows = (f.strip() for f in fields)
            rows.append(
                {
                    "name": name,
                    "created_epoch": int(created) if created.isdigit() else None,
                    "attached": attached == "1",
                    "windows": int(windows) if windows.isdigit() else None,
                }
            )
        rows.sort(key=lambda r: r["created_epoch"] or 0, reverse=True)
        return rows

    def half_built_windows(self) -> list[dict[str, Any]] | None:
        """Windows on this frame that a build began and never finished.

        A frame window has three panes, each tagged with its role. ONE pane with no
        role tag is a build that created the window and then aborted before tagging
        it — and because nothing maps a session to an untagged window, such a window
        can never be selected from the sidebar. So it is invisible except as
        clutter, while its sidebar keep-alive re-probes tmux once a second forever.
        Fourteen accumulated for a single session on 2026-10-22, when a launch
        refusal raised mid-build; `build` now tears its own window down, so these
        are either residue from before that fix or a new abort worth knowing about.

        Scoped to this frame's OWN session rather than the whole socket: an
        unmanaged session sharing the socket legitimately has untagged one-pane
        windows, and reporting those would make this finding noise.

        Returns [] for "scanned, none found" and **None** for "could not scan" —
        three states, not two. Collapsing the scan failure into an empty list let
        `verify` report a confidently healthy frame on a check that never ran, which
        is the whole reason `incomplete` exists.
        """
        if not self.exists():
            return []
        result = self.tmux(
            [
                "list-panes",
                "-s",
                "-t",
                self.target,
                "-F",
                "#{window_id}\t#{window_name}\t#{@hive_ide_pane}",
            ]
        )
        if result.returncode != 0:
            return None             # could not look; not the same as nothing there
        panes: dict[str, list[tuple[str, str]]] = {}
        for line in result.stdout.splitlines():
            fields = line.split("\t")
            if len(fields) != 3:
                continue
            window, name, role = (f.strip() for f in fields)
            panes.setdefault(window, []).append((name, role))
        out = [
            {"window": window, "name": rows[0][0]}
            for window, rows in panes.items()
            if len(rows) == 1 and not rows[0][1]
        ]
        return sorted(out, key=lambda row: row["window"])

    def unmanaged_sessions(self) -> list[dict[str, Any]]:
        """Sessions on this socket that are not this frame.

        A frame owns exactly one tmux session, so anything else sharing its socket
        is something nobody is tracking. One host was found carrying two `_preheat`
        sessions eight days after they were created — unattached, one shell window,
        no ide hooks. A warm-up session is not meant to outlive its warm-up, and it
        is what keeps an otherwise-idle server alive long enough to accumulate the
        duplicate clients that reflow windows and, on the `select` backend macOS
        forces tmux onto, can spin a core.

        Reported rather than reaped on purpose: nothing in this package creates a
        `_preheat` session — it appears on no branch, in no tag, and in no installed
        copy — so there is no producer to guard against and no safe general rule for
        killing someone else's tmux session. Naming it is the durable part.
        """
        return [s for s in self.tmux_sessions() if s["name"] != self.target]

    def windows(self) -> dict[str, str]:
        if not self.exists():
            return {}
        result = self.tmux(
            [
                "list-windows",
                "-t",
                self.target,
                "-F",
                "#{@hive_ide_session_id}\t#{window_id}",
            ]
        )
        if result.returncode != 0:
            return {}
        rows: dict[str, str] = {}
        for line in result.stdout.splitlines():
            session_id, _, window_id = line.partition("\t")
            if session_id:
                rows[session_id] = window_id
        return rows

    def role_panes(self, session_id: str) -> dict[str, str] | None:
        """Role -> pane id for the session's window.

        `{}` means the window is absent or carries no tagged panes. `None` means the
        panes could not be observed (`list-panes` failed); callers must treat that as
        unknown and never destroy anything on the strength of it.
        """
        window_id = self.windows().get(session_id)
        if not window_id:
            return {}
        return self._role_panes_in_window(window_id)

    # -- caller identity ---------------------------------------------------
    #
    # Three environment inputs describe where the calling process lives:
    # `TMUX_PANE` (the pane, set by tmux), `TMUX` (`<socket-path>,<pid>,<session>`,
    # set by tmux) and the IDE marker `HIVE_IDE_TMUX_SOCKET` (the `-L` name the
    # frame spawned the pane with). A pane id is unique only within one server, so
    # the pane means nothing until the server is known. Every verdict below is
    # tri-state and fails CLOSED: incomplete or self-contradictory evidence is
    # `None`, never "outside", because "outside" is what authorizes a kill.

    @staticmethod
    def caller_pane() -> str | None:
        """The tmux pane this process runs in, if any (`$TMUX_PANE`)."""
        return os.environ.get("TMUX_PANE") or None

    def socket_path(self) -> str:
        """The socket path `tmux -L <self.socket>` resolves to for this process."""
        base = os.environ.get("TMUX_TMPDIR") or "/tmp"
        return os.path.join(base, f"tmux-{os.getuid()}", self.socket)

    @staticmethod
    def tmux_var_socket_path(value: str | None) -> str | None:
        """The socket path from a well-formed `$TMUX` (`<abs-path>,<pid>,<session>`).

        Anything else — a missing field, a non-numeric pid or session, a relative
        or empty path — is malformed and yields None: malformed evidence is
        unknown, never a claim about which server the caller is on.
        """
        if not value:
            return None
        parts = value.split(",")
        if len(parts) != 3:
            return None
        path, pid, session = parts
        if not path or not os.path.isabs(path) or not pid.isdigit() or not session.isdigit():
            return None
        return path

    def _tmux_var_verdict(self) -> bool | None:
        """Does `$TMUX` name this server? `None` when absent or malformed."""
        path = self.tmux_var_socket_path(os.environ.get("TMUX"))
        if path is None:
            return None
        expected = self.socket_path()
        if os.path.normpath(path) == os.path.normpath(expected):
            return True
        try:
            return os.path.realpath(path) == os.path.realpath(expected)
        except OSError:
            return None

    def caller_server(self) -> bool | None:
        """Is the caller on THIS frame's tmux server? Tri-state.

        `False` only when there is no tmux evidence at all (a plain terminal, a
        daemon) or when the marker and a well-formed `$TMUX` BOTH name a different
        server. `True` only when the evidence present agrees the caller is on this
        server. Anything else — a pane with no server evidence, a marker without
        `$TMUX` that names another server, a marker and `$TMUX` that disagree, a
        `$TMUX` that does not parse — is `None`.
        """
        pane = self.caller_pane()
        marker = os.environ.get("HIVE_IDE_TMUX_SOCKET") or None
        tmux = os.environ.get("TMUX") or None
        if not pane and not marker and not tmux:
            return False
        by_marker = (marker == self.socket) if marker else None
        by_tmux = self._tmux_var_verdict() if tmux else None
        if tmux and by_tmux is None:
            # Present but malformed: evidence that cannot be read is not evidence
            # of another server, and it leaves the marker unconfirmed.
            return None
        if by_marker is None and by_tmux is None:
            return None
        if by_marker is None:
            return True if by_tmux else None
        if by_tmux is None:
            return True if by_marker else None
        if by_marker and by_tmux:
            return True
        if not by_marker and not by_tmux:
            return False
        return None

    def pane_still_is(
        self, pane_id: str, *, role: str, session_id: str, tty: str
    ) -> bool:
        """Re-verify, in ONE round trip, that a pane is still what we resolved it to be.

        Used while a descriptor on `tty` is already open. Everything it checks can
        change between resolving a pane and writing to it: the pane can die (and the
        kernel re-issue its `/dev/pts/N` to someone else), `relayout --mode=adopt` runs
        on the same hook and can move the sidebar role to a different pane, and the
        window could have been rebuilt under a different session.

        One `display-message` rather than three calls, because this sits on the window
        switch path — the three-call version measured 144ms to a repainted sidebar
        against 88ms for this one.
        """
        result = self.tmux(
            [
                "display-message",
                "-p",
                "-t",
                pane_id,
                "#{pane_dead}\t#{pane_tty}\t#{@hive_ide_pane}\t#{@hive_ide_session_id}",
            ]
        )
        if result.returncode != 0:
            return False
        fields = result.stdout.strip().split("\t")
        if len(fields) != 4:
            return False
        dead, pane_tty, pane_role, pane_session = (f.strip() for f in fields)
        return (
            dead != "1"
            and pane_tty == tty
            and pane_role == role
            and pane_session == session_id
        )

    def pane_tty(self, pane_id: str) -> str:
        """A LIVE pane's tty device, or "" when tmux cannot say it is live.

        A process outside the pane can paint it by writing here: tmux owns the master
        side, so bytes written to the slave are rendered as that pane's own output.
        That is how a window switch repaints a sidebar WITHOUT respawning the pane,
        which would clear it and leave it blank until an interpreter started.

        Liveness is not a nicety, it is the whole safety of the mechanism. A pane kept
        after its process exited (`remain-on-exit`) still REPORTS its old tty, tmux has
        already closed that pty's master, and the kernel is free to hand the same
        `/dev/pts/N` to the next pane that opens one. Writing to the dead pane's
        reported path then paints a completely unrelated pane — reproduced on an
        isolated server during review, and it needs no race to happen. So a dead pane,
        a pane tmux will not describe, and a pane with no tty all return "", and the
        caller leaves the stale frame alone rather than guessing.
        """
        result = self.tmux(
            ["display-message", "-p", "-t", pane_id, "#{pane_dead}\t#{pane_tty}"]
        )
        if result.returncode != 0:
            return ""
        dead, _, tty = result.stdout.strip().partition("\t")
        if dead.strip() == "1":
            return ""
        tty = tty.strip()
        return tty if tty.startswith("/dev/") else ""

    def pane_is_caller(self, pane_id: str) -> bool | None:
        """Is `pane_id` the pane this process runs in? Tri-state.

        Destructive pane helpers act only on an exact `False`.
        """
        server = self.caller_server()
        if server is False:
            return False
        pane = self.caller_pane()
        if not pane and server is True and self._tmux_var_verdict() is True:
            # tmux itself places us on this server and gave us no pane: tmux
            # exports `$TMUX_PANE` into every pane it creates, so a process on
            # this server without one is a popup, a `run-shell` or a hook — none
            # of which can BE the pane in question. Reading that as "cannot tell"
            # is what stopped the sidebar waking a sleeping agent, because the
            # options modal runs in a popup.
            #
            # `$TMUX` is required here, not just the marker. The marker is an
            # ordinary environment variable that a process can inherit from
            # somewhere else, so marker-only evidence stays unknown.
            return False
        if server is None or not pane:
            return None
        return pane == pane_id

    def pane_ids(self, window_id: str) -> list[str] | None:
        """Every pane id in the window, or `None` when they cannot be observed."""
        result = self.tmux(["list-panes", "-t", window_id, "-F", "#{pane_id}"])
        if result.returncode != 0:
            return None
        return [line.strip() for line in result.stdout.splitlines() if line.strip()]

    def caller_location(self, window_id: str) -> bool | None:
        """Is the caller inside `window_id`? Tri-state.

        `False` is a verdict: the caller is provably outside — not in tmux at all,
        on a server that both the marker and `$TMUX` say is a different one, or in
        a listed pane of some other window on this server. `True` is a verdict the
        other way. `None` covers everything that cannot be settled: partial or
        conflicting server evidence, a server match without a pane id, or a
        window whose panes could not be listed. A destructive caller treats `None`
        as "possibly inside".
        """
        server = self.caller_server()
        if server is False:
            return False
        caller = self.caller_pane()
        if server is None or not caller:
            return None
        panes = self.pane_ids(window_id)
        if panes is None:
            return None
        return caller in panes

    def caller_in_window(self, window_id: str) -> bool:
        """True only when the caller pane is listed in `window_id` on this server."""
        return self.caller_location(window_id) is True

    def pane_hive_ide_env(self, pane_id: str) -> dict[str, str] | None:
        """The `HIVE_IDE_*` environment of the pane's own root process.

        The pane's identity is what tmux spawned it with: the `-e` values live in
        the environment of `#{pane_pid}`, the `sh -c` wrapper. Descendants are
        not evidence — an agent runs background jobs that drop or override
        `HIVE_IDE_SESSION_ID` for their own subprocesses, so a deeper process
        can both mask a genuine mismatch of the pane and fake one on a healthy
        pane. The root's environ is therefore the answer whenever it is
        readable, HIVE_IDE_ keys or not. Only when it cannot be read do the
        root's DIRECT children stand in, in pid order and never deeper: the
        first with an IDE key answers, else `{}` if any was readable.

        `{}` means an environment was read and carries no IDE identity. `None`
        means nothing could be observed: the pane's pid did not resolve, or
        neither the root nor any direct child had a readable environment.
        """
        pid = self._pane_pid(pane_id)
        if pid is None:
            return None
        root = self._process_env(pid)
        if root:
            return self._hive_ide_keys(root)
        readable = False
        for child in sorted(self._child_pids(pid)):
            env = self._process_env(child)
            if not env:
                continue
            readable = True
            identity = self._hive_ide_keys(env)
            if identity:
                return identity
        return {} if readable else None

    @staticmethod
    def _hive_ide_keys(env: dict[str, str]) -> dict[str, str]:
        return {key: value for key, value in env.items() if key.startswith("HIVE_IDE_")}

    @staticmethod
    def _child_pids(pid: int) -> list[int]:
        """Direct children of `pid` (from procfs), unordered; `[]` when unreadable."""
        children = Path(f"/proc/{pid}/task/{pid}/children")
        try:
            return [
                int(item)
                for item in children.read_text(encoding="utf-8").split()
                if item.isdigit()
            ]
        except OSError:
            return []

    def _pane_pid(self, pane_id: str) -> int | None:
        result = self.tmux(["display-message", "-p", "-t", pane_id, "#{pane_pid}"])
        if result.returncode != 0:
            return None
        value = result.stdout.strip()
        return int(value) if value.isdigit() else None

    @staticmethod
    def _process_tree(pid: int) -> list[int]:
        seen: set[int] = set()
        ordered: list[int] = []
        stack = [pid]
        while stack:
            current = stack.pop()
            if current in seen:
                continue
            seen.add(current)
            ordered.append(current)
            stack.extend(Frame._child_pids(current))
        return ordered

    @staticmethod
    def _process_env(pid: int) -> dict[str, str]:
        try:
            raw = Path(f"/proc/{pid}/environ").read_bytes()
        except OSError:
            return {}
        env: dict[str, str] = {}
        for item in raw.split(b"\0"):
            if b"=" not in item:
                continue
            key, value = item.split(b"=", 1)
            try:
                env[key.decode("utf-8")] = value.decode("utf-8", errors="replace")
            except UnicodeDecodeError:
                continue
        return env

    def _role_panes_in_window(self, window_id: str) -> dict[str, str] | None:
        result = self.tmux(
            [
                "list-panes",
                "-t",
                window_id,
                "-F",
                "#{@hive_ide_pane}\t#{pane_id}",
            ]
        )
        if result.returncode != 0:
            # Unobservable is not "no panes": a failed listing must never read as
            # "every role is missing" and license a rebuild.
            return None
        return {
            role: pane_id
            for line in result.stdout.splitlines()
            for role, _, pane_id in [line.partition("\t")]
            if role and pane_id
        }

    def _pane_indices(self, window_id: str) -> dict[int, str]:
        result = self.tmux(
            [
                "list-panes",
                "-t",
                window_id,
                "-F",
                "#{pane_index}\t#{pane_id}",
            ]
        )
        if result.returncode != 0:
            return {}
        rows: dict[int, str] = {}
        for line in result.stdout.splitlines():
            index, _, pane_id = line.partition("\t")
            if index.isdigit() and pane_id:
                rows[int(index)] = pane_id
        return rows

    def _pane_rows(self, window_id: str) -> list[tuple[int, str, str]]:
        result = self.tmux(
            [
                "list-panes",
                "-t",
                window_id,
                "-F",
                "#{pane_index}\t#{pane_id}\t#{@hive_ide_pane}",
            ]
        )
        if result.returncode != 0:
            return []
        rows: list[tuple[int, str, str]] = []
        for line in result.stdout.splitlines():
            index, pane_id, role = (
                line.split("\t") if line.count("\t") == 2 else ("", "", "")
            )
            if index.isdigit() and pane_id:
                rows.append((int(index), pane_id, role))
        return rows

    def _order_role_panes(self, window_id: str) -> dict[str, str]:
        rows = self._pane_rows(window_id)
        roles = {role: pane_id for _, pane_id, role in rows if role}
        if set(self.PANE_ROLES) - set(roles):
            return roles
        for _ in range(len(self.PANE_ROLES)):
            changed = False
            rows = self._pane_rows(window_id)
            by_index = {index: (pane_id, role) for index, pane_id, role in rows}
            by_role = {role: index for index, _, role in rows if role}
            for index, role in enumerate(self.PANE_ROLES):
                current = by_index.get(index)
                if current and current[1] == role:
                    continue
                source_index = by_role.get(role)
                if source_index is None:
                    continue
                self.tmux(
                    [
                        "swap-pane",
                        "-d",
                        "-s",
                        f"{window_id}.{source_index}",
                        "-t",
                        f"{window_id}.{index}",
                    ]
                )
                changed = True
                break
            if not changed:
                break
        return self._role_panes_in_window(window_id) or {}

    def _module(
        self, module: str, args: list[str], *, interpreter: str | None = None
    ) -> str:
        return PythonCommand.module_command(
            module, args, python=interpreter or self.python
        )

    def _environment(self, record: dict[str, Any], *, role: str | None = None) -> list[str]:
        source = record.get("source") or {}
        env = [
            "-e",
            f"HIVE_IDE_PROTOCOL_VERSION={PROTOCOL_VERSION}",
            "-e",
            f"HIVE_IDE_VERSION={__version__}",
            "-e",
            f"HIVE_IDE_STATE_HOME={self.store.home}",
            "-e",
            f"HIVE_IDE_WORKSPACE_KEY={self.store.workspace_key}",
            "-e",
            f"HIVE_IDE_TMUX_SOCKET={self.socket}",
            "-e",
            f"HIVE_IDE_SESSION_ID={record['id']}",
            "-e",
            f"HIVE_IDE_SESSION={record['name']}",
            "-e",
            f"HIVE_IDE_SOURCE={source.get('kind') or 'stable'}",
        ]
        hive = (record.get("host") or {}).get("hive") or {}
        repo = hive.get("repo")
